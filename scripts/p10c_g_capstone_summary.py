#!/usr/bin/env python
"""Render the concise P10C-G Capstone evaluation summary from MACHINE-READABLE results that were produced by the existing runners. It measures nothing itself: every figure in the output carries
the commit, date and environment profile of the run that produced it, and a coverage figure is only printed for a profile that was actually supplied (never copied from another profile or from
history).

    python scripts/p10c_g_capstone_summary.py --global G.json --coverage DEV.json [--coverage CLEAN.json] --out SUMMARY.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def render(g: dict, covs: list[dict]) -> str:
    profs = {c["profile"] for c in covs}
    if len(profs) != len(covs):
        raise SystemExit("two coverage reports for the same profile were supplied")
    c0 = g["corpus"]
    m = g["matrix"]
    out = ["# P10C-G Capstone evaluation summary (generated)", "",
           "Generated by `scripts/p10c_g_capstone_summary.py` from the machine-readable results of `scripts/eval_global_corpus.py` and `scripts/check_product_coverage_baseline.py`. Each figure names its run.", "",
           "## 1. Global synthetic evaluation (offline; synthetic fixtures; no store, network or model)",
           f"- corpus v{g['corpus_version']}: **{c0['passed']}/{c0['total']}** cases passed; governance and negative regressions **{sum(x['ok'] for x in g['governance'])}/{len(g['governance'])}**; "
           f"required evidence tags **{m['exercised']}/{m['required_tags']}** exercised",
           f"- deterministic across {g['repeat']} repeated runs: **{g['deterministic_across_runs']}**; existing P10C evaluators: " + ", ".join(f"{k.replace('eval_', '')} {v['checks']} checks ({'ok' if not v['failed'] else 'FAILED'})" for k, v in g["existing_evaluators"].items()),
           f"- resolver latency over {g['latency']['resolve_samples']} corpus requests: p50 {g['latency']['resolve_p50_ms']} ms, p95 {g['latency']['resolve_p95_ms']} ms; fixture rebuild {g['latency']['fixture_rebuild_seconds']} s",
           "- claims: product ready False; human qualified False; source qualified globally False; runtime approved False; 95% gate passed False", "",
           "## 2. Product coverage (the existing 412-case evaluator; two environment profiles; never combined)",
           "| Profile | Run (commit, date, tracked files modified) | Stores present | Sufficient / cases | Insufficient | Regressions | Improvements | REGRESSION STATUS | PRODUCT COVERAGE GATE (392 required) |", "|---|---|---|---|---|---|---|---|---|"]
    for c in sorted(covs, key=lambda x: x["profile"]):
        stores = sum(1 for v in c["store_availability"].values() if v)
        out.append(f"| {c['profile']} | `{c['commit'][:10]}`, {c['executed_at'][:10]}, {c.get('tracked_files_modified_since_commit')} | {stores}/{len(c['store_availability'])} | {c['sufficient']}/{c['total_cases']} ({100 * c['sufficient'] / c['total_cases']:.1f}%) | "
                   f"{c['insufficient']} | {len(c['regressions'])} | {len(c['improvements'])} | **{c['regression_status']}** | **{c['product_coverage_gate']}** |")
    missing = {"developer_local", "clean_checkout"} - profs
    for p in sorted(missing):
        out.append(f"| {p} | NOT RUN in this summary | n/a | n/a | n/a | n/a | n/a | n/a | n/a |")
    out += ["", "The two profiles are different measurements (the evaluator reads git-ignored local knowledge stores when they exist). Both are BELOW the unchanged 95% threshold; the owner accepted the observed baselines for the Capstone engineering scope as an accepted limitation, not a pass. A regression PASS means no previously sufficient case regressed; it does not mean the gate passed.", "",
            "## 3. Verdicts", "- GLOBAL SYNTHETIC EVALUATION: " + ("PASS" if g["ok"] else "FAIL"), "- REGRESSION STATUS: " + ", ".join(f"{c['profile']} {c['regression_status']}" for c in sorted(covs, key=lambda x: x["profile"])),
            "- PRODUCT COVERAGE GATE: " + ", ".join(f"{c['profile']} {c['product_coverage_gate']}" for c in sorted(covs, key=lambda x: x["profile"])), ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--global", dest="glob", required=True)
    ap.add_argument("--coverage", action="append", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    g = json.loads(Path(a.glob).read_text())
    covs = [json.loads(Path(p).read_text()) for p in a.coverage]
    Path(a.out).write_text(render(g, covs), encoding="utf-8")
    print("summary written:", a.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
