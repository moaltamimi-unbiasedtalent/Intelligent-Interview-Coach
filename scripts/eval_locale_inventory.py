#!/usr/bin/env python
"""06A per-language locale inventory (LG-01) and readiness-record validation (LG-13).

Offline and deterministic: no provider call, no network. Imports ``tests.conftest`` first (test isolation).
Writes ONLY to a temp directory unless ``--write`` is given (then the committed audit table
``docs/production/execution/evidence/06A_LOCALE_AUDIT.md`` is regenerated). ``--check`` fails when the committed
audit table is stale. The generated table is byte-stable (no timestamps), so it can be compared.

The inventory reports seven active candidate languages (en, de, es, it, pt, fr, nl) and, separately, Russian
as EXCLUDED and PRESERVED. Nothing here qualifies a language: that needs every gate LG-01..LG-14 with evidence.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import tests.conftest  # noqa: E402,F401  (test isolation: temp DB, no .env)

ROOT = Path(__file__).resolve().parent.parent
FE = ROOT / "frontend"
AUDIT_PATH = ROOT / "docs/production/execution/evidence/06A_LOCALE_AUDIT.md"
READINESS_PATH = ROOT / "docs/production/execution/language_readiness.json"

GATES = tuple(f"LG-{i:02d}" for i in range(1, 15))
STATES = ("NOT STARTED", "NOT RUN", "ENGINEERING DRAFT", "PASS")
ORDER = ("en", "de", "es", "it", "pt", "fr", "nl")  # the register's stated order
EXCLUDED = ("ru",)


def catalogue_stats() -> dict[str, dict] | None:
    node = shutil.which("node")
    if node is None:
        return None
    proc = subprocess.run([node, "scripts/dump-catalog-stats.mjs"], cwd=str(FE), capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"catalogue stats helper failed: {proc.stderr.strip()[:300]}")
    return json.loads(proc.stdout)


def backend_stats(code: str) -> dict:
    from src import prompts
    from src.agent.policies import RESPONSE_LANGUAGE_NAMES
    from src.copilot.rag import localized as loc
    from src.locales import LANGUAGE_NAMES
    from src.mail import templates as mail

    def has(table) -> int:
        return 1 if code in table else 0

    mo_tables = ("SECTION_HEADINGS", "INSUFFICIENT", "FALLBACK", "COMPENSATION_GUIDANCE", "UNVERIFIED_GENERAL", "UNRETRIEVED_LIMITATION",
                 "IRRELEVANT_SOURCES", "SOURCE_LANGUAGE_NOTICE")
    mo_present = sum(has(getattr(loc, t)) for t in mo_tables)
    mail_kinds = mail._T.get(code, {})
    return {
        "mo_templates": f"{mo_present}/{len(mo_tables)}",
        "directives": f"{has(LANGUAGE_NAMES) + has(prompts._CONVERSATION_LANGUAGE_NAMES) + has(RESPONSE_LANGUAGE_NAMES)}/3",
        "email_templates": f"{sum(1 for k in mail.KINDS if k in mail_kinds)}/{len(mail.KINDS)}",
    }


def load_readiness() -> dict:
    return json.loads(READINESS_PATH.read_text(encoding="utf-8"))


def readiness_problems(data: dict) -> list[str]:
    """Structural and honesty checks on the readiness record (used by the audit and by the tests)."""
    from src.locales import ACTIVE_CANDIDATE_LOCALES

    problems: list[str] = []
    langs = data.get("languages", {})
    for code in ACTIVE_CANDIDATE_LOCALES:
        rec = langs.get(code)
        if rec is None:
            problems.append(f"{code}: no readiness record")
            continue
        gates = rec.get("gates", {})
        for g in GATES:
            e = gates.get(g)
            if e is None:
                problems.append(f"{code}/{g}: missing gate record")
                continue
            if e.get("state") not in STATES:
                problems.append(f"{code}/{g}: invalid state {e.get('state')!r}")
            if e.get("state") == "PASS" and not (e.get("evidence") or "").strip():
                problems.append(f"{code}/{g}: PASS without evidence reference")
        if rec.get("production_qualified") is True and not all(gates.get(g, {}).get("state") == "PASS" for g in GATES):
            problems.append(f"{code}: production_qualified without every gate PASS")
    return problems


def build_markdown() -> str:
    from src.locales import ACTIVE_CANDIDATE_LOCALES, SUPPORTED_LOCALE_CODES

    stats = catalogue_stats()
    data = load_readiness()
    out: list[str] = []
    w = out.append
    w("# 06A Locale audit (LG-01)")
    w("")
    w("Generated by `python scripts/eval_locale_inventory.py --write` (offline, deterministic, no provider call). Do not edit by hand.")
    w("")
    w("**Status: ENGINEERING INVENTORY. No language is production-qualified.** A language is qualified only when every gate LG-01 to LG-14 has passed for it with evidence "
      "(`docs/production/MULTILINGUAL_RELEASE_QUALIFICATION.md`). The per-language, per-gate record is `docs/production/execution/language_readiness.json`.")
    w("")
    w(f"Active Candidate locales (code-defined in `src/locales.py`, served by `GET /api/v1/capabilities`): {', '.join(ACTIVE_CANDIDATE_LOCALES)}. "
      f"Stored/catalogue locales: {', '.join(SUPPORTED_LOCALE_CODES)} (Russian preserved, excluded from selection).")
    w("")
    w("## 1. Interface catalogues and companion text, per language")
    w("")
    w("| Language | Interface keys | Missing vs en | Extra vs en | Blank | Placeholder mismatches | Identical to English (possible leak or brand/token) | Legal/trust keys | Mo templates | Directives | Email templates | Translation review status |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for code in ORDER:
        b = backend_stats(code)
        s = (stats or {}).get(code)
        if s:
            cols = f"{s['keys']} | {s['missing_vs_en']} | {s['extra_vs_en']} | {s['blank_values']} | {s['placeholder_mismatches']} | {s['identical_to_english']} | {s['legal_namespace_keys']}"
        else:
            cols = "n/a | n/a | n/a | n/a | n/a | n/a | n/a"
        status = "source language (no translation)" if code == "en" else "engineering translation, NOT natively reviewed"
        w(f"| {code} | {cols} | {b['mo_templates']} | {b['directives']} | {b['email_templates']} | {status} |")
    w("")
    if stats is None:
        w("_Catalogue statistics need `node` (not found in this environment)._")
        w("")
    w("Flagged as unreviewed engineering translations: every non-English interface key (all languages above except `en`), every Mo localized template, every email template and every legal/trust string. "
      "No native-reviewer or legal-qualification record exists yet (gates LG-10 and LG-11 are NOT STARTED).")
    w("")
    w("## 2. Excluded and preserved: Russian")
    w("")
    w("| Language | Interface keys | Missing vs en | Mo templates | Directives | Email templates | State |")
    w("|---|---|---|---|---|---|---|")
    for code in EXCLUDED:
        b = backend_stats(code)
        s = (stats or {}).get(code)
        keys = s["keys"] if s else "n/a"
        miss = s["missing_vs_en"] if s else "n/a"
        w(f"| {code} | {keys} | {miss} | {b['mo_templates']} | {b['directives']} | {b['email_templates']} | EXCLUDED from R1.0 Candidate selection; code, catalogue and tests PRESERVED; not part of any qualification claim |")
    w("")
    w("## 3. Interview and report language directives")
    w("")
    w("The interview (Practice) generation language is a bounded `conversation_language` turned into a trusted, allow-list-only directive by `src/prompts.py` (`_CONVERSATION_LANGUAGE_NAMES`, built from `src.locales.LANGUAGE_NAMES`); "
      "Mo uses `src/agent/policies.py` (`RESPONSE_LANGUAGE_NAMES`). The directives are prose-only. Per-language behaviour of these directives against a live model has NOT been run (LG-04, LG-05 NOT STARTED).")
    w("")
    w("## 4. Legal, privacy and email coverage")
    w("")
    w("Legal and trust pages (terms, privacy, AI transparency, trust) are present as catalogue keys in every language (column above) but are engineering translations; qualified legal translation (LG-10) has NOT started. "
      "Transactional emails exist for every locale in `src/mail/templates.py` (plain text, protected slogan unchanged) as engineering translations.")
    w("")
    w("## 5. Per-language gate state (from `language_readiness.json`)")
    w("")
    w("| Language | " + " | ".join(GATES) + " | All gates passed |")
    w("|---|" + "---|" * (len(GATES) + 1))
    for code in ORDER:
        rec = data["languages"].get(code, {})
        cells = [rec.get("gates", {}).get(g, {}).get("state", "MISSING") for g in GATES]
        w(f"| {code} | " + " | ".join(cells) + f" | {'YES' if rec.get('production_qualified') else 'NO'} |")
    w("")
    probs = readiness_problems(data)
    w(f"Readiness record integrity problems: {len(probs)}" + ("" if not probs else " (" + "; ".join(probs) + ")"))
    w("")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="regenerate the committed audit table")
    ap.add_argument("--check", action="store_true", help="fail if the committed audit table is stale")
    args = ap.parse_args()
    text = build_markdown()
    if args.write:
        AUDIT_PATH.parent.mkdir(parents=True, exist_ok=True)
        AUDIT_PATH.write_text(text, encoding="utf-8")
        print(f"wrote {AUDIT_PATH.relative_to(ROOT)}")
    else:
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / "06A_LOCALE_AUDIT.md"
            p.write_text(text, encoding="utf-8")
            print(f"generated {p} ({len(text)} bytes; not written to the repository)")
    problems = readiness_problems(load_readiness())
    for p in problems:
        print("PROBLEM:", p)
    stale = False
    if args.check:
        stale = not AUDIT_PATH.exists() or AUDIT_PATH.read_text(encoding="utf-8") != text
        print("audit table stale" if stale else "audit table current")
    print("Paid LLM calls: 0   Live calls: 0")
    return 1 if (problems or stale) else 0


if __name__ == "__main__":
    raise SystemExit(main())
