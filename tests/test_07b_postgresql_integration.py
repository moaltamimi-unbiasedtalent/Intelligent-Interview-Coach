class Database:
    def __init__(self, postgres):
        self.port = postgres.port
        self.database = "p5b_07b_" + uuid4().hex
        self.bootstrap = "p5b_checkpoint_test_" + postgres.token

    def url(self, actor):
        return f"postgresql+psycopg://{actor}:{PASSWORD}@127.0.0.1:{self.port}/{self.database}"

    def connect(self, actor="disposable", *, bootstrap=False, database_name=None, autocommit=True):
        import psycopg

        return psycopg.connect(
            host="127.0.0.1", hostaddr="127.0.0.1", port=self.port,
            dbname=database_name or (self.bootstrap if bootstrap else self.database), user=actor, password=PASSWORD,
            connect_timeout=3, options="-c statement_timeout=5000 -c lock_timeout=3000", autocommit=autocommit,
        )

    def query(self, statement, args=(), *, actor="disposable"):
        with self.connect(actor) as connection:
            cursor = connection.execute(statement, args)
            return cursor.fetchall() if cursor.description else None

    def provision(self, name):
        from psycopg import sql

        with self.connect(bootstrap=True) as admin:
            # Bound the WAL generated by repeated fixture database creation.
            admin.execute(sql.SQL("CREATE DATABASE {} STRATEGY FILE_COPY").format(sql.Identifier(name)))
            admin.execute(sql.SQL("REVOKE CREATE, TEMPORARY ON DATABASE {} FROM PUBLIC").format(sql.Identifier(name)))
        with self.connect(database_name=name) as admin, admin.transaction():
            admin.execute(DDL.read_text())
            return admin.execute("SELECT ledger_id FROM ask4mo_07b.control").fetchone()[0]

    def bind(self, name, config):
        from psycopg.types.json import Jsonb

        with self.connect(database_name=name) as admin:
            admin.execute("UPDATE ask4mo_07b.control SET policy = %s", (Jsonb(database_policy(config)),))

    def drop(self, name):
        from psycopg import sql

        with self.connect(bootstrap=True) as admin:
            admin.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))

    @property
    def policy_json(self):
        return json.dumps(database_policy(self.policy))

    @property
    def reserve_floor(self):
        return database_policy(self.policy)["operations"]["ragas"]["reservation_micro_usd"]

    def reserve_sql(self):
        return self.query(RESERVE, (self.policy_json, MODEL, "d" * 64, self.reserve_floor), actor=RUNTIME_ROLE)[0]

    def accept_sql(self, entry, token):
        self.query("SELECT ask4mo_07b.accept_handoff(%s, %s, %s::jsonb)", (entry, token, self.policy_json), actor=RUNTIME_ROLE)

    def issue(self, kind, generation, *, entry=None, cost=None, expired=False, actor=RECONCILE):
        authorization = uuid4()
        self.query("""
            INSERT INTO ask4mo_07b.authorization (id, kind, actor, generation, reservation_id, final_micro_usd, expires_at)
            VALUES (%s, %s, %s, %s, %s, %s, clock_timestamp() + %s::interval)
        """, (authorization, kind, actor, generation, entry, cost, "-1 minute" if expired else "1 hour"), actor=ISSUER)
        return authorization


