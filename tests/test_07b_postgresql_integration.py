def test_concurrent_and_abandoned_reservation_cannot_be_replayed_or_resumed(database):
    db = database
    entered = threading.Event()
    release = threading.Event()

    def handler(request):
        entered.set()
        assert release.wait(5)
        return ok(request)

    first, second = build(db), build(db)
    with ThreadPoolExecutor(max_workers=1) as pool:
        future = pool.submit(_dispatch, first, _request(), handler)
        try:
            assert entered.wait(5)
            with pytest.raises(BudgetError) as error:
                _dispatch(second, _request(), lambda _: pytest.fail("unexpected duplicate dispatch"))
            assert error.value.reason == "duplicate_in_flight"
            with pytest.raises(BudgetError) as error:
                _dispatch(second, _request(body=_chat("second synthetic request")),
                          lambda _: pytest.fail("unexpected concurrent dispatch"))
            assert error.value.reason == "concurrency_limit"
            assert first.status()["calls_by_state"] == {"reserved": 1}
        finally:
            release.set()
        assert future.result(timeout=5).status_code == 200

    reservation = second.ledger.reserve(
        db.policy, budget_class="evaluation", category="evaluation", operation="ragas", model=MODEL,
        endpoint="chat", fingerprint="a" * 64, worst_case=100, governed_07b=True,
    )
    second.ledger.accept_07b_handoff(reservation, lambda: None)
    db.query("SELECT ask4mo_07b.emergency_stop()", actor=STOP)
    approval = db.issue("resume", 1)
    denied(db, RECONCILE, "SELECT ask4mo_07b.resume(1, %s)", (approval,),
           state="P0001", reason="recovery_reconciliation_required")
    denied(db, RECONCILE, "SELECT ask4mo_07b.mark_abandoned(%s, %s)", (reservation.entry_id, uuid4()),
           state="P0001", reason="authorization_invalid")
    abandon = db.issue("abandoned", 1, entry=reservation.entry_id)
    db.query("SELECT ask4mo_07b.mark_abandoned(%s, %s)", (reservation.entry_id, abandon), actor=RECONCILE)
    assert db.query("SELECT state, held_micro_usd FROM ask4mo_07b.entry WHERE id = %s", (reservation.entry_id,)) == [
        ("unknown", db.reserve_floor),
    ]


