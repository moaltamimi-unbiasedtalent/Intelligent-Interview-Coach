def test_async_cancel_during_database_handoff_never_dispatches(database, monkeypatch):
    db = database
    gov = build(db)
    entered, release = threading.Event(), threading.Event()
    handoff = gov.ledger.accept_07b_handoff

    def wait_for_cancellation(reservation, accept):
        entered.set()
        assert release.wait(5)
        return handoff(reservation, accept)

    monkeypatch.setattr(gov.ledger, "accept_07b_handoff", wait_for_cancellation)

    async def scenario():
        async with gov.prototype_client(lambda _: pytest.fail("cancelled request dispatched"), asynchronous=True) as client:
            task = asyncio.create_task(gov.send_async(httpx.AsyncClient.send, client, _request(), {}))
            try:
                assert await asyncio.to_thread(entered.wait, 5)
                task.cancel()
                with pytest.raises(asyncio.CancelledError):
                    await task
            finally:
                release.set()

    asyncio.run(scenario())  # Joins the receiver thread before inspecting its rollback.
    assert db.query("SELECT state, accepted_at FROM ask4mo_07b.entry") == [("rejected", None)]


