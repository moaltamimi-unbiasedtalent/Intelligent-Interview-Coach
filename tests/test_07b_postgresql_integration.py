def test_stop_operator_commits_after_contended_control_lock(database):
    db = database
    waiting = threading.Event()
    pids = []

    def stop():
        with db.connect(STOP) as session:
            pids.append(session.info.backend_pid)
            waiting.set()
            session.execute("SELECT ask4mo_07b.emergency_stop()")

    with ThreadPoolExecutor(max_workers=1) as pool:
        with db.connect() as locker, locker.transaction():
            locker.execute("SELECT singleton FROM ask4mo_07b.control FOR UPDATE")
            stopped = pool.submit(stop)
            assert waiting.wait(5)
            deadline = time.monotonic() + 2
